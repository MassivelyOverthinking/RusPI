use serde::{Deserialize, Serialize};

//===========================================================================================================================
// RESPONSE
//===========================================================================================================================

#[derive(Debug, Deserialize)]
pub struct PredictRequest {
    pub input: Vec<f32>,
}

#[derive(Debug, Serialize)]
pub struct PredictResponse {
    pub output: Vec<f32>,
}
